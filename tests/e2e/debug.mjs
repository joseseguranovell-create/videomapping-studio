import { createRequire } from 'node:module';
import fs from 'node:fs'; import path from 'node:path'; import os from 'node:os';
const require = createRequire(import.meta.url);
const { _electron: electron } = require('playwright');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'vms-'));
const env = { ...process.env, VMSTUDIO_USER_DATA: path.join(tmp, 'ud'), VMSTUDIO_DOCUMENTS: path.join(tmp, 'docs') };
delete env.NODE_OPTIONS;
const app = await electron.launch({ executablePath: require('electron'), args: ['.', '--no-sandbox'], env });
const win = await app.firstWindow();
win.on('pageerror', (e) => console.log(`[pageerror] ${e.message}`));
win.on('console', (m) => m.type() === 'error' && console.log(`[console] ${m.text()}`));
await win.waitForSelector('.app');
await win.click('[data-testid="example-halloween-infantil"]');
await win.fill('[data-testid="dialog-input"]', 'Casa');
await win.click('[data-testid="dialog-ok"]');
await win.waitForSelector('[data-testid="timeline"]', { timeout: 15000 });
await win.waitForTimeout(1500);
const dom = await win.evaluate(() => {
  const g = document.querySelector('[data-testid=preview-gl]');
  const o = document.querySelector('.preview-frame .ov');
  const f = document.querySelector('.preview-frame');
  const cs = (e) => { const s = getComputedStyle(e); return { pos: s.position, w: s.width, h: s.height, op: s.opacity, vis: s.visibility, z: s.zIndex, bg: s.backgroundColor }; };
  return { g: g.getBoundingClientRect().toJSON(), o: o.getBoundingClientRect().toJSON(), f: f.getBoundingClientRect().toJSON(), gs: cs(g), os: cs(o), ow: o.width, oh: o.height, gw: g.width };
});
console.log(JSON.stringify(dom));
const r = await win.evaluate(() => {
  const p = window.__vmPreviewPlayer;
  p.seek(45);
  p.renderFrame();
  const px = [];
  for (const [x, y] of [[0.34, 0.43], [0.5, 0.2], [0.05, 0.9], [0.5, 0.75]]) px.push(p.r.readPixel(x * p.canvas.width, y * p.canvas.height));
  return { mode: p.mode, inst: p.currentInstallation()?.name, w: p.canvas.width, h: p.canvas.height, gpu: p.r.rendererName, err: p.errors, px, glErr: p.r.gl.getError(), status: p.status() };
});
await win.evaluate(() => { const p = window.__vmPreviewPlayer; p.seek(45); });
await win.waitForTimeout(800);
await win.locator('.preview-frame').screenshot({ path: process.env.SHOTS + '/pv-a.png' });
await win.evaluate(() => { document.querySelector('.preview-frame .ov').style.display = 'none'; });
await win.waitForTimeout(800);
await win.locator('.preview-frame').screenshot({ path: process.env.SHOTS + '/pv-b.png' });
const data = await win.evaluate(() => { const p = window.__vmPreviewPlayer; p.renderFrame(); return p.canvas.toDataURL('image/png'); });
fs.writeFileSync(process.env.SHOTS + '/pv-c.png', Buffer.from(data.split(',')[1], 'base64'));
await app.close();
