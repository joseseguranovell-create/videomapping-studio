import { createRequire } from 'node:module';
import fs from 'node:fs'; import path from 'node:path'; import os from 'node:os';
const require = createRequire(import.meta.url);
const { _electron: electron } = require('playwright');
const out = process.env.SHOTS;
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'vms-'));
const env = { ...process.env, VMSTUDIO_USER_DATA: path.join(tmp, 'ud'), VMSTUDIO_DOCUMENTS: path.join(tmp, 'docs') };
delete env.NODE_OPTIONS;
const app = await electron.launch({ executablePath: require('electron'), args: ['.', '--no-sandbox'], env });
const win = await app.firstWindow();
const logs = [];
win.on('console', (m) => logs.push(`[${m.type()}] ${m.text()}`));
win.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await win.waitForSelector('.app');
await app.evaluate(({ BrowserWindow }) => { const w = BrowserWindow.getAllWindows()[0]; w.setSize(1600, 1000); });
await win.click('[data-testid="example-halloween-infantil"]');
await win.fill('[data-testid="dialog-input"]', 'Casa Halloween');
await win.click('[data-testid="dialog-ok"]');
await win.waitForSelector('[data-testid="timeline"]', { timeout: 15000 });
await win.waitForTimeout(2500);
await win.screenshot({ path: `${out}/shows.png` });
await win.click('[data-testid="scene-block-5"]');
await win.waitForTimeout(1500);
await win.click('[data-testid="preview-play"]');
await win.waitForTimeout(2500);
await win.screenshot({ path: `${out}/shows-play.png` });
await win.click('[data-testid="nav-calibrate"]');
await win.waitForTimeout(1500);
await win.click('[data-testid="surface-item-2"]');
await win.waitForTimeout(800);
await win.screenshot({ path: `${out}/calibrate.png` });
await win.click('[data-testid="nav-library"]');
await win.waitForTimeout(1000);
await win.screenshot({ path: `${out}/library.png` });
await win.click('[data-testid="nav-characters"]');
await win.waitForTimeout(1500);
await win.screenshot({ path: `${out}/characters.png` });
console.log(logs.filter((l) => !l.includes('Electron Security')).join('\n'));
await app.close();
